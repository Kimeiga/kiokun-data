				caption="One push → 28 parallel lanes → 28 repositories, each replaced wholesale."
			>
				<DiagramPipeline />
			</Figure>
		</Reveal>

		<Reveal as="section">
			<h2><span class="num">IV</span> Don't upload what you can generate</h2>
			<p>
				This is the part worth internalising. Building the dictionary locally and pushing
				the result means 435,000 files — hundreds of megabytes — have to climb my home
				upload link to reach GitHub. The compute is fast; the <em>transfer</em> is the wall.
			</p>
			<p>
				Generating in CI inverts it. I push a few kilobytes of Rust. The runner builds and
				commits <em>inside GitHub's own network</em>, a few milliseconds from the
				destination repositories. The heavy bytes are born where they need to live and
				never travel over a residential connection at all.
			</p>
		</Reveal>

		<Reveal as="div">
