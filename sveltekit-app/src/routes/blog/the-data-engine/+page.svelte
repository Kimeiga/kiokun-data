			<p class="lede">
				<span class="dropcap">K</span>iokun is a Chinese–Japanese–Korean dictionary. Look up a
				character and you get readings, senses, decompositions, example sentences — a dense
				little dossier per entry, and there are about <b>435,000</b> of them. Early on this
				lived in Cloudflare R2, an object store that bills per request and per gigabyte. It
				worked. It also meant a meter ran every time someone tapped a word.
			</p>
			<p>
				The replacement has no storage bill at all. It is a pile of public GitHub
				repositories, addressed by arithmetic, and rebuilt by the same push that ships the
				code. This is how the pieces fit.
			</p>
		</Reveal>

		<Reveal as="section">
			<h2><span class="num">I</span> One word, one path</h2>
			<p>
				There is no lookup table and no search index. Given a word, the client computes
				where its file lives. The address has two coordinates, and a single integer hash
				produces both.
			</p>
			<p>
				First, the word is classified by how many Han characters it contains — none, one,
				two, or three-plus. That picks a <em>family</em> of repositories. Within the family,
				<code>hash % N</code> chooses the specific repo, and the low byte of that very same
				hash, <code>hash &amp; 0xff</code>, chooses one of 256 subdirectories. The hash is a
				plain rolling <code>h = h·31 + c</code> — trivial on purpose, because the Rust
				generator and the TypeScript client must agree to the bit.
			</p>
		</Reveal>

		<Reveal as="div">
			<Figure
				n={1}
				bleed
				title="Addressing"
				caption="Han-count selects a family; one hash fixes both the repository and the subdirectory."
			>
				<DiagramRouter />
			</Figure>
		</Reveal>

		<Reveal as="section">
			<p>
				The payoff: resolving a word is <em>pure computation</em>. The browser builds a
				URL and fetches one deflate-compressed JSON file. No round-trip to ask "where is
				it?" — the question answers itself.
			</p>
		</Reveal>

		<Reveal as="section">
			<h2><span class="num">II</span> The 256-folder trick</h2>
			<p>
				Spreading files across thirty repositories keeps any single repo around ten to
				thirteen thousand files. That alone isn't enough. Git — and GitHub's UI, API, and
				the CDNs that mirror it — get unhappy with directories that hold tens of thousands
				of entries. A flat folder of 45,000 files is a slow folder.
			</p>
			<blockquote>
				So the second coordinate isn't decoration. It's the difference between a directory
				of forty files and a directory of forty-five thousand.
			</blockquote>
			<p>
				Hence <code>00</code> through <code>ff</code>: 256 subdirectories per repo, each
				holding a comfortable few dozen files. The commit tree for a shard drops from
				~26&nbsp;MB to single digits, and every level of the stack — git, GitHub, jsDelivr —
				stays in its happy path.
			</p>
		</Reveal>

		<Reveal as="div">
			<Figure
				n={2}
				bleed
				title="Fan-out"
				caption="30 repositories, and 256 hash-keyed subdirectories inside each one."
			>
				<DiagramShardMap />
			</Figure>
		</Reveal>

		<Reveal as="section">
			<h2><span class="num">III</span> The build runs itself</h2>
			<p>
				The dictionary is generated by Rust from upstream sources — JMdict, Kanjidic2,
				JMnedict and friends. The interesting part isn't the parsing; it's that I never run
				it. A push to <code>kiokun-data</code> that touches <code>src/**</code> or
				<code>Cargo.toml</code> triggers a GitHub Actions workflow whose matrix has one entry
				per active shard. Twenty-eight jobs start at once.
			</p>
			<p>
				Each lane compiles the generator, runs
				<code>build_dictionary --mode &lt;shard&gt; --prod</code>, then clones its target
				repo, lays down the files, and commits onto a fresh <em>orphan</em> branch that is
				force-pushed over <code>main</code>. No history is kept — each deploy is a clean
				snapshot, which is exactly why the repos stay small.
			</p>
		</Reveal>

		<Reveal as="div">
			<Figure
				n={3}
				bleed
