		</Reveal>

		<Reveal as="section">
			<h2><span class="num">V</span> The bill, and the fine print</h2>
			<p>
				Hosting: <b>$0/month</b>. Static files on public GitHub repos, served through raw
				URLs and jsDelivr's global CDN, with no egress meter. The honest tradeoffs: deploys
				are eventually consistent while 28 repos settle; force-pushing orphan branches is a
				deliberate amnesia, not an accident; and raw GitHub is preferred over jsDelivr in
				production specifically to dodge cross-region cache skew.
			</p>
			<p>
				None of this is exotic. It's a hash function, a folder convention, and a CI matrix
				pointed at the obvious conclusion — that the cheapest, fastest place to assemble a
				large dataset is next to where it will be served. <span class="end-seal"
					aria-hidden="true"></span>
			</p>
